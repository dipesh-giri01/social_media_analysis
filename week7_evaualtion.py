print("TESTING SET — CLASSIFICATION PERFORMANCE")
print("=" * 70)
print(f"  Accuracy : {test_accuracy:.4f}  ({test_accuracy * 100:.2f}%)")
print(f"  Precision: {test_precision:.4f}")
print(f"  Recall   : {test_recall:.4f}")
print(f"  F1-Score : {test_f1:.4f}")
print("\nClassification Report (Testing):")
print(classification_report(y_test, y_test_pred, target_names=["Low Engagement", "High Engagement"]))
print("Confusion Matrix (Testing):")
print(cm_test)
print(f"  TN={cm_test[0,0]}  FP={cm_test[0,1]}  FN={cm_test[1,0]}  TP={cm_test[1,1]}")

