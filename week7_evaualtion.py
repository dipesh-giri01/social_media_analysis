import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split, StratifiedKFold, cross_validate
from sklearn.neural_network import MLPClassifier, MLPRegressor
from sklearn.metrics import (
  classification_report,
  confusion_matrix,
  accuracy_score,
  precision_score,
  recall_score,
  f1_score,
  mean_squared_error,
  mean_absolute_error,
  r2_score,
  roc_curve,
  auc,
)
import warnings

warnings.filterwarnings("ignore")

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 1 — LOAD & INSPECT DATASET
# ─────────────────────────────────────────────────────────────────────────────
print("=" * 70)
print("MLP Model — Evaluation & Refinement  |  AIT 500 Project")
print("Dipesh Giri, Simon Sharma, Kushal Gautam")
print("=" * 70)

print("\n[1] Loading Dataset...")
url = "https://raw.githubusercontent.com/dipesh-giri01/social_media_analysis/refs/heads/main/train_cleaned.csv"
# df = pd.read_csv("train_cleaned.csv") for local
# for collab
df = pd.read_csv(url)
print(f"Dataset shape: {df.shape}  ({df.shape[0]} rows, {df.shape[1]} columns)")
print(f"\nFirst 5 rows:\n{df.head()}")

print("\n[2] Dataset Information:")
print(df.info())
print("\nDescriptive Statistics:")
print(df.describe())

print("\nMissing Values:")
print(df.isnull().sum())

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 2 — FEATURE SELECTION & TARGET ENGINEERING
# ─────────────────────────────────────────────────────────────────────────────
print("\n[3] Feature Selection and Engineering:")
print("  MLPClassifier — 10 features → binary high/low engagement (median likes threshold)")
print("  MLPRegressor  — 7 features  → predict likes, shares, comments (multi-output)")

features_clf = [
  "platform_encoded",
  "post_type_encoded",
  "likes",
  "shares",
  "comments",
  "views",
  "year",
  "month",
  "day_of_week",
  "week_of_year",
]

features_reg = [
  "platform_encoded",
  "post_type_encoded",
  "views",
  "year",
  "month",
  "day_of_week",
  "week_of_year",
]

engagement_threshold = df["likes"].median()
y = (df["likes"] > engagement_threshold).astype(int)

print(f"\nEngagement threshold (median likes): {engagement_threshold}")
print(f"  Low Engagement  (0): {(y == 0).sum()} samples")
print(f"  High Engagement (1): {(y == 1).sum()} samples")

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 3 — FEATURE SCALING & TRAIN/TEST SPLIT
# ─────────────────────────────────────────────────────────────────────────────
print("\n[4] Feature Scaling (StandardScaler — zero mean, unit variance):")
X = df[features_clf]
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)
print("  Applied to all 10 MLPClassifier input features.")
for i, col in enumerate(features_clf):
  print(f"    {col:<22}  mean={scaler.mean_[i]:.3f}, std={scaler.scale_[i]:.3f}")

X_reg = df[features_reg]
scaler_reg = StandardScaler()
X_reg_scaled = scaler_reg.fit_transform(X_reg)
y_reg = df[["likes", "shares", "comments"]].values

print("\n[5] Train / Test Split (80 / 20, stratified, random_state=42):")
X_train, X_test, y_train, y_test = train_test_split(
  X_scaled, y, test_size=0.2, random_state=42, stratify=y
)
X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(
  X_reg_scaled, y_reg, test_size=0.2, random_state=42
)

print(f"  Training : {len(X_train)} samples")
print(f"  Testing  : {len(X_test)} samples")
print(f"  Train class dist → Low: {(y_train == 0).sum()}  High: {(y_train == 1).sum()}")
print(f"  Test  class dist → Low: {(y_test == 0).sum()}   High: {(y_test == 1).sum()}")

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 4 — MODEL ARCHITECTURE & TRAINING
# ─────────────────────────────────────────────────────────────────────────────
print("\n[6] MLP Model Architecture:")
print("  Hidden layers : (100, 50)")
print("  Activation    : ReLU")
print("  Solver        : Adam (adaptive learning rate)")
print("  Max iterations: 300")
print("  Early stopping: enabled (patience=20, val_fraction=0.10)")

mlp_clf = MLPClassifier(
  hidden_layer_sizes=(100, 50),
  activation="relu",
  solver="adam",
  learning_rate="adaptive",
  max_iter=300,
  random_state=42,
  early_stopping=True,
  validation_fraction=0.1,
  n_iter_no_change=20,
  verbose=0,
)

mlp_reg = MLPRegressor(
  hidden_layer_sizes=(100, 50),
  activation="relu",
  solver="adam",
  learning_rate="adaptive",
  max_iter=300,
  random_state=42,
  early_stopping=True,
  validation_fraction=0.1,
  n_iter_no_change=20,
)

print("\n[7] Training MLPClassifier...")
mlp_clf.fit(X_train, y_train)
print(f"  ✓ Done — converged at iteration {mlp_clf.n_iter_}, final loss: {mlp_clf.loss_:.4f}")

print("\n[7b] Training MLPRegressor (multi-output: likes, shares, comments)...")
mlp_reg.fit(X_train_reg, y_train_reg)
print(f"  ✓ Done — converged at iteration {mlp_reg.n_iter_}, final loss: {mlp_reg.loss_:.4f}")

# ─────────────────────────────────────────────────────────────────────────────
# SECTION 5 — CLASSIFICATION EVALUATION
# ─────────────────────────────────────────────────────────────────────────────
y_train_pred = mlp_clf.predict(X_train)
y_test_pred = mlp_clf.predict(X_test)

train_accuracy  = accuracy_score(y_train, y_train_pred)
train_precision = precision_score(y_train, y_train_pred)
train_recall    = recall_score(y_train, y_train_pred)
train_f1        = f1_score(y_train, y_train_pred)

test_accuracy  = accuracy_score(y_test, y_test_pred)
test_precision = precision_score(y_test, y_test_pred)
test_recall    = recall_score(y_test, y_test_pred)
test_f1        = f1_score(y_test, y_test_pred)

cm_train = confusion_matrix(y_train, y_train_pred)
cm_test  = confusion_matrix(y_test,  y_test_pred)

print("\n" + "=" * 70)
print("TRAINING SET — CLASSIFICATION PERFORMANCE")
print("=" * 70)
print(f"  Accuracy : {train_accuracy:.4f}  ({train_accuracy * 100:.2f}%)")
print(f"  Precision: {train_precision:.4f}")
print(f"  Recall   : {train_recall:.4f}")
