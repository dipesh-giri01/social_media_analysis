print(f'Average R² (uniform over targets): {reg_r2:.4f}')
for i, name in enumerate(reg_targets):
  print(f'  {name}: MAE={mae_per[i]:.2f}, MSE={mse_per[i]:.2f}, R²={r2_per[i]:.4f}')

