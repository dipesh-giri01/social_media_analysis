import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.model_selection import train_test_split
from sklearn.neural_network import MLPClassifier, MLPRegressor
from sklearn.metrics import (
  classification_report,
  confusion_matrix,
  accuracy_score,
  precision_score,
  recall_score,
  f1_score,
  mean_squared_error,
  mean_absolute_error,
  r2_score,
  roc_curve,
  auc,
)
import warnings

warnings.filterwarnings('ignore')

print('='*70)
print('MLP Model Training and Testing - AIT 500 Project')
print('='*70)

# Load the cleaned dataset
print('\n[1] Loading Dataset...')
print('\n[1] Loading Dataset...')
url = "https://raw.githubusercontent.com/dipesh-giri01/social_media_analysis/refs/heads/main/train_cleaned.csv"
df = pd.read_csv(url)
print(f'Dataset shape: {df.shape}')
print(f'Rows: {df.shape[0]}, Columns: {df.shape[1]}')
print('\nFirst few rows:')
print(df.head())

# Display feature information
print('\n[2] Dataset Information:')
print(df.info())
print('\nDataset Statistics:')
print(df.describe())

# Check for missing values
print('\nMissing Values:')
print(df.isnull().sum())

# Define features and target
print('\n[3] Feature Selection and Engineering:')
print('MLPClassifier — 10 scaled features → high vs low engagement (median likes threshold).')
print('MLPRegressor — platform, post type, views, dates → predicts likes, shares, comments (multi-output).')

# Classification (same feature list as course snippet)
features_clf = [
  'platform_encoded',
  'post_type_encoded',
  'likes',
  'shares',
  'comments',
  'views',
  'year',
  'month',
  'day_of_week',
  'week_of_year',
]
X = df[features_clf]

# Regression targets (multi-output); inputs must not include those targets
features_reg = [
  'platform_encoded',
  'post_type_encoded',
  'views',
  'year',
  'month',
  'day_of_week',
  'week_of_year',
]

# Create target variable: High engagement (1) vs Low engagement (0)
# Using median of likes as threshold for binary classification
engagement_threshold = df['likes'].median()
y = (df['likes'] > engagement_threshold).astype(int)

print(f'\nTarget Variable: High Engagement Classification')
print(f'Threshold (Median Likes): {engagement_threshold}')
print(f'Class Distribution:')
print(f'  Low Engagement (0): {(y == 0).sum()} samples')
print(f'  High Engagement (1): {(y == 1).sum()} samples')

# Feature Scaling
print('\n[4] Feature Scaling:')
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)
print('Applied StandardScaler to all MLPClassifier inputs (10 features)')
print(f'Scaled feature range: Mean≈0, Std≈1')
print(f'\nScaling parameters:')
for i, col in enumerate(features_clf):
  print(f'  {col}: mean={scaler.mean_[i]:.2f}, std={scaler.scale_[i]:.2f}')

# Train-Test Split
print('\n[5] Train-Test Split:')
X_train, X_test, y_train, y_test = train_test_split(
  X_scaled, y, test_size=0.2, random_state=42
)

X_reg = df[features_reg]
scaler_reg = StandardScaler()
X_reg_scaled = scaler_reg.fit_transform(X_reg)
y_reg = df[['likes', 'shares', 'comments']].values
X_train_reg, X_test_reg, y_train_reg, y_test_reg = train_test_split(
  X_reg_scaled, y_reg, test_size=0.2, random_state=42
)

print(f'Total samples: {len(X_scaled)}')
print(f'Training set: {len(X_train)} samples (80%)')
print(f'Testing set: {len(X_test)} samples (20%)')
print(f'\nTraining set class distribution:')
print(f'  Low Engagement: {(y_train == 0).sum()} samples')
print(f'  High Engagement: {(y_train == 1).sum()} samples')
print(f'\nTesting set class distribution:')
print(f'  Low Engagement: {(y_test == 0).sum()} samples')
print(f'  High Engagement: {(y_test == 1).sum()} samples')

# MLP Model Configuration
print('\n[6] MLP Model Configuration:')
print('Model Architecture:')
print('  Hidden layers: (100, 50)')
print('    - Layer 1: 100 neurons')
print('    - Layer 2: 50 neurons')
print('  Activation function: ReLU (Rectified Linear Unit)')
print('  Solver/Optimizer: Adam')
print('  Learning rate: Adaptive')
print('  Max iterations: 300')
print('  Random state: 42')

mlp_model = MLPClassifier(
  hidden_layer_sizes=(100, 50),
  activation='relu',
  solver='adam',
  learning_rate='adaptive',
  max_iter=300,
  random_state=42,
  early_stopping=True,
  validation_fraction=0.1,
  n_iter_no_change=20,
  verbose=0,
)

# Train the model
print('\n[7] Training the MLP Model:')
print('Training in progress...')
mlp_model.fit(X_train, y_train)
print('✓ MLPClassifier training completed!')
print(f'Converged at iteration: {mlp_model.n_iter_}')
print(f'Final training loss:    {mlp_model.loss_:.4f}')

# MLPClassifier — training loss + validation score (same structure as course snippet)
if hasattr(mlp_model, 'loss_curve_') and mlp_model.loss_curve_ is not None:
  loss_curve = np.asarray(mlp_model.loss_curve_, dtype=float)
  n_curve = len(loss_curve)
  epochs = np.arange(n_curve)
  conv_idx = n_curve - 1

  fig_lc, ax1_lc = plt.subplots(figsize=(10, 6))
  ax1_lc.plot(epochs, loss_curve, color='steelblue', linewidth=2, label='Training Loss')
  ax1_lc.set_xlabel('Epoch / Iteration', fontsize=12)
  ax1_lc.set_ylabel('Training Loss', color='steelblue', fontsize=12)
  ax1_lc.tick_params(axis='y', labelcolor='steelblue')

  ax2_lc = None
  val_scores = getattr(mlp_model, 'validation_scores_', None)
  if val_scores is not None and len(val_scores) > 0:
    val_scores = np.asarray(val_scores, dtype=float)
    val_epochs = np.arange(len(val_scores))
    ax2_lc = ax1_lc.twinx()
    ax2_lc.plot(
      val_epochs,
      val_scores,
      color='coral',
      linewidth=2,
      linestyle='--',
      label='Validation Score',
    )
    ax2_lc.set_ylabel('Validation Score', color='coral', fontsize=12)
    ax2_lc.tick_params(axis='y', labelcolor='coral')

  ax1_lc.axvline(
    x=conv_idx,
    color='green',
    linestyle=':',
    linewidth=1.8,
    label=f'Early Stop (iter {mlp_model.n_iter_})',
  )
  if conv_idx >= 0:
    ann_x = min(conv_idx + 1.5, n_curve + 0.5)
    ax1_lc.annotate(
      f'Stopped at\niteration {mlp_model.n_iter_}',
      xy=(conv_idx, loss_curve[conv_idx]),
      xytext=(ann_x, float(loss_curve[0]) * 0.6),
      arrowprops=dict(arrowstyle='->', color='green'),
      fontsize=10,
      color='green',
    )

  lines1, labels1 = ax1_lc.get_legend_handles_labels()
  if ax2_lc is not None:
    lines2, labels2 = ax2_lc.get_legend_handles_labels()
    ax1_lc.legend(lines1 + lines2, labels1 + labels2, loc='center right', fontsize=10)
  else:
    ax1_lc.legend(lines1, labels1, loc='center right', fontsize=10)

  ax1_lc.set_title(
    f'MLP Classifier — Training Loss Curve (Converged at Iteration {mlp_model.n_iter_})',
    fontweight='bold',
    fontsize=13,
  )
  ax1_lc.grid(alpha=0.3)
  plt.tight_layout()
  plt.savefig('loss_curve.png', dpi=300, bbox_inches='tight')
  plt.close(fig_lc)
  print('✓ Saved loss_curve.png (MLPClassifier: 10 features, median-likes label, early stopping)')

print('\n[7b] Training MLP Regressor (predict likes, shares, comments):')
mlp_reg = MLPRegressor(
  hidden_layer_sizes=(100, 50),
  activation='relu',
  solver='adam',
  max_iter=300,
  random_state=42,
)
mlp_reg.fit(X_train_reg, y_train_reg)
print('✓ MLPRegressor training completed!')
print(f'Converged at iteration: {mlp_reg.n_iter_}')
print(f'Final training loss:    {mlp_reg.loss_:.4f}')

# MLPRegressor — training loss curve (multi-output; no validation curve unless early_stopping is enabled)
if hasattr(mlp_reg, 'loss_curve_') and mlp_reg.loss_curve_ is not None:
  reg_lc = np.asarray(mlp_reg.loss_curve_, dtype=float)
  reg_epochs = np.arange(len(reg_lc))
  fig_rl, ax_rl = plt.subplots(figsize=(10, 6))
  ax_rl.plot(reg_epochs, reg_lc, color='darkviolet', linewidth=2, label='Training Loss')
  ax_rl.set_xlabel('Epoch / Iteration', fontsize=12)
  ax_rl.set_ylabel('Training Loss', fontsize=12)
  ax_rl.set_title(
    f'MLP Regressor — Training Loss Curve (n_iter={mlp_reg.n_iter_})',
    fontweight='bold',
    fontsize=13,
  )
  ax_rl.legend(loc='upper right', fontsize=10)
  ax_rl.grid(alpha=0.3)
  plt.tight_layout()
  plt.savefig('loss_curve_regressor.png', dpi=300, bbox_inches='tight')
  plt.close(fig_rl)
  print('✓ Saved loss_curve_regressor.png (MLPRegressor: 3 targets, Adam + ReLU)')

# Combined figure: classifier vs regressor training loss (one image for reports)
if (
  hasattr(mlp_model, 'loss_curve_') and mlp_model.loss_curve_ is not None
  and hasattr(mlp_reg, 'loss_curve_') and mlp_reg.loss_curve_ is not None
):
  lc_c = np.asarray(mlp_model.loss_curve_, dtype=float)
  lc_r = np.asarray(mlp_reg.loss_curve_, dtype=float)
  fig_both, (ax_c, ax_r) = plt.subplots(1, 2, figsize=(14, 5.2), constrained_layout=True)
  fig_both.suptitle('MLP training loss — classifier vs regressor', fontsize=14, fontweight='bold')

  ep_c = np.arange(len(lc_c))
  ax_c.plot(ep_c, lc_c, color='steelblue', linewidth=2, label='Training loss')
  ax_c.set_xlabel('Epoch / iteration', fontsize=11)
  ax_c.set_ylabel('Training loss', color='steelblue', fontsize=11)
  ax_c.tick_params(axis='y', labelcolor='steelblue')
  val_b = getattr(mlp_model, 'validation_scores_', None)
  if val_b is not None and len(val_b) > 0:
    val_b = np.asarray(val_b, dtype=float)
    ax_cv = ax_c.twinx()
    ax_cv.plot(np.arange(len(val_b)), val_b, color='coral', linestyle='--', linewidth=2, label='Validation score')
    ax_cv.set_ylabel('Validation score', color='coral', fontsize=11)
    ax_cv.tick_params(axis='y', labelcolor='coral')
    h1, l1 = ax_c.get_legend_handles_labels()
    h2, l2 = ax_cv.get_legend_handles_labels()
    ax_c.legend(h1 + h2, l1 + l2, loc='upper right', fontsize=9)
  else:
    ax_c.legend(loc='upper right', fontsize=9)
  ax_c.set_title(f'MLPClassifier (n_iter={mlp_model.n_iter_})', fontweight='bold', fontsize=12)
  ax_c.grid(alpha=0.3)

  ep_r = np.arange(len(lc_r))
  ax_r.plot(ep_r, lc_r, color='darkviolet', linewidth=2, label='Training loss')
  ax_r.set_xlabel('Epoch / iteration', fontsize=11)
  ax_r.set_ylabel('Training loss', fontsize=11)
  ax_r.set_title(f'MLPRegressor (n_iter={mlp_reg.n_iter_})', fontweight='bold', fontsize=12)
  ax_r.legend(loc='upper right', fontsize=9)
  ax_r.grid(alpha=0.3)

  plt.savefig('11_mlp_training_loss_classifier_and_regressor.png', dpi=300, bbox_inches='tight', facecolor='white')
  plt.close(fig_both)
  print('✓ Saved 11_mlp_training_loss_classifier_and_regressor.png')

# Make predictions
print('\n[8] Model Predictions:')
y_train_pred = mlp_model.predict(X_train)
y_test_pred = mlp_model.predict(X_test)

# Evaluate on training set
print('\n' + '='*70)
print('TRAINING SET PERFORMANCE')
print('='*70)
train_accuracy = accuracy_score(y_train, y_train_pred)
train_precision = precision_score(y_train, y_train_pred)
